// function declation

function add(a, b) {
  return a + b;
}

console.log(add(10, 40));
console.log(add(1, 4));
console.log(add(13, 20));
console.log(add(16, 34));
console.log(add(30, 90));

// function expression

const addition = function (a, b) {
  return a + b;
};

console.log(addition(10, 40));
console.log(addition(1, 4));
console.log(addition(13, 20));
console.log(addition(16, 34));
console.log(addition(30, 90));
